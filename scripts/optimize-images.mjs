const out = "public/img";
fs.mkdirSync(out, { recursive: true });
const data = {};
for (const [slug, rel] of Object.entries(map)) {
  const src = path.join(R, rel);
  const img = sharp(src).rotate();
  const buf = await img.resize({ width: 2000, height: 2000, fit: "inside", withoutEnlargement: true }).webp({ quality: 78 }).toBuffer({ resolveWithObject: true });
  fs.writeFileSync(path.join(out, slug + ".webp"), buf.data);
  const blur = await sharp(buf.data).resize(14).blur(1).webp({ quality: 40 }).toBuffer();
  data[slug] = { src: `/img/${slug}.webp`, w: buf.info.width, h: buf.info.height, blur: "data:image/webp;base64," + blur.toString("base64") };
  console.log(slug, buf.info.width + "x" + buf.info.height, Math.round(buf.data.length / 1024) + "kB");
}
fs.mkdirSync("lib", { recursive: true });
fs.writeFileSync("lib/photos.generated.ts", `// generated by scripts/optimize-images.mjs — do not edit\nexport const photos = ${JSON.stringify(data, null, 2)} as const;\nexport type PhotoKey = keyof typeof photos;\n`);

